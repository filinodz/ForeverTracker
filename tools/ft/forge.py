"""The Forge: ready-to-apply SQL that adds what the server lacks, each with its rollback.

    hotfix    copies the official client records of a resource (and the records they depend on that the
              server lacks) into the hotfixes database, so the core knows it.
    trainer   teaches a class or profession spell at the trainers that already teach its skill line.
    instance  creates the instance_template row of a dungeon or raid.

Selling items through a vendor is generated by the website, since the administrator picks the vendor.
"""
import os
import re
import statistics

from . import sqlio
from .content import table
from .rules import L
from .server import log, server_db2

SPELL_TABLES = ['SpellMisc', 'SpellEffect', 'SpellLevels', 'SpellPower', 'SpellCooldowns', 'SpellCategories', 'SpellCastingRequirements',
                'SpellAuraOptions', 'SpellAuraRestrictions', 'SpellInterrupts', 'SpellClassOptions', 'SpellReagents', 'SpellReagentsCurrency',
                'SpellShapeshift', 'SpellTargetRestrictions', 'SpellTotems', 'SpellXSpellVisual', 'SpellEquippedItems', 'SpellScaling',
                'SpellLabel', 'SpellLearnSpell', 'SpellEmpower']


def money(copper, gold, silver, cop):
    """12345 -> '1g 23s 45c' (zero parts left out)."""
    parts = [(copper // 10000, gold), (copper // 100 % 100, silver), (copper % 100, cop)]
    text = ' '.join(f'{value}{unit}' for value, unit in parts if value)
    return text or f'0{cop}'


def snake(name):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', name).lower()


class Copier:
    """Collects client records missing on the server and writes their INSERT / DELETE statements."""

    def __init__(self, folder, build):
        self.folder, self.build = folder, build
        self.columns, self.types = {}, {}
        bits = {'tinyint': 8, 'smallint': 16, 'mediumint': 24, 'int': 32, 'bigint': 64}
        for row in sqlio.query("SELECT TABLE_NAME t, COLUMN_NAME c, DATA_TYPE d, COLUMN_TYPE ct FROM information_schema.columns WHERE table_schema = DATABASE() ORDER BY TABLE_NAME, ORDINAL_POSITION", 'hotfixes'):
            self.columns.setdefault(row['t'], []).append(row['c'])
            if row['d'] in bits:
                self.types[(row['t'], row['c'])] = (bits[row['d']], 'unsigned' in row['ct'])
        self._known, self._rows, self._index, self._hash = {}, {}, {}, {}

    def rows(self, name, locale='frFR'):
        key = (name, locale)
        if key not in self._rows:
            self._rows[key] = {r['ID']: r for r in table(self.folder, name, locale)}
        return self._rows[key]

    def where(self, name, column, value):
        key = (name, column)
        if key not in self._index:
            index = {}
            for row in self.rows(name).values():
                index.setdefault(row.get(column), []).append(row)
            self._index[key] = index
        return self._index[key].get(value, [])

    def known(self, name, record_id):
        if name not in self._known:
            ids = {r['ID'] for r in server_db2(name)}
            if snake(name) in self.columns:
                ids |= {int(x) for x in sqlio.column(f'SELECT ID FROM `{snake(name)}`', 'hotfixes')}
            self._known[name] = ids
        return record_id in self._known[name]

    def table_hash(self, name):
        if name not in self._hash:
            from .content import table_hash
            self._hash[name] = table_hash(self.folder, name)
        return self._hash[name]

    # ---------- plans: {(Table, ID)} of client records missing on the server ----------
    def add(self, plan, name, record_id):
        if record_id and record_id in self.rows(name) and not self.known(name, record_id) and snake(name) in self.columns:
            plan.add((name, record_id))
            return True
        return False

    def spell(self, plan, spell_id, depth=0):
        if ('SpellName', spell_id) in plan:
            return
        if not self.add(plan, 'SpellName', spell_id) and depth:
            return  # a referenced spell the server already knows
        for name in SPELL_TABLES:
            for row in self.where(name, 'SpellID', spell_id):
                self.add(plan, name, row['ID'])
                if name == 'SpellMisc':
                    self.add(plan, 'SpellDuration', row['DurationIndex'])
                    self.add(plan, 'SpellRange', row['RangeIndex'])
                    self.add(plan, 'SpellCastTimes', row['CastingTimeIndex'])
                elif name == 'SpellEffect':
                    self.add(plan, 'SpellRadius', row['EffectRadiusIndex1'])
                    self.add(plan, 'SpellRadius', row['EffectRadiusIndex2'])
                    if row['EffectTriggerSpell'] and depth < 2:
                        self.spell(plan, row['EffectTriggerSpell'], depth + 1)
                elif name == 'SpellCategories':
                    for key in ('Category', 'StartRecoveryCategory', 'ChargeCategory'):
                        self.add(plan, 'SpellCategory', row[key])
        for row in self.where('SkillLineAbility', 'Spell', spell_id):
            self.add(plan, 'SkillLineAbility', row['ID'])

    def item(self, plan, item_id):
        for name in ('Item', 'ItemSparse', 'ItemSearchName'):
            self.add(plan, name, item_id)
        for link in self.where('ItemXItemEffect', 'ItemID', item_id):
            self.add(plan, 'ItemXItemEffect', link['ID'])
            effect = self.rows('ItemEffect').get(link['ItemEffectID'])
            if effect:
                self.add(plan, 'ItemEffect', effect['ID'])
                if effect['SpellID']:
                    self.spell(plan, effect['SpellID'], 1)
        for appearance in self.where('ItemModifiedAppearance', 'ItemID', item_id):
            self.add(plan, 'ItemModifiedAppearance', appearance['ID'])
            self.add(plan, 'ItemAppearance', appearance['ItemAppearanceID'])

    def achievement(self, plan, ach_id):
        self.add(plan, 'Achievement', ach_id)
        root = self.rows('Achievement').get(ach_id, {}).get('CriteriaTree')
        stack, seen = [root] if root else [], set()
        while stack:
            tree_id = stack.pop()
            if tree_id in seen:
                continue
            seen.add(tree_id)
            node = self.rows('CriteriaTree').get(tree_id)
            if not node:
                continue
            self.add(plan, 'CriteriaTree', tree_id)
            if node['CriteriaID']:
                self.add(plan, 'Criteria', node['CriteriaID'])
            stack.extend(child['ID'] for child in self.where('CriteriaTree', 'Parent', tree_id))

    # ---------- SQL ----------
    def fit(self, target, column, value):
        """The same bits in the column's own integer type (the core reads DB2 values as raw bits too)."""
        kind = self.types.get((target, column))
        if not kind or not isinstance(value, int):
            return value
        size, unsigned = kind
        value &= (1 << size) - 1
        return value if unsigned or value < 1 << (size - 1) else value - (1 << size)

    def sql(self, plan):
        """(apply, rollback, rows, push) for a plan."""
        apply, rollback, push = [], [], []
        by_table = {}
        for name, record_id in sorted(plan):
            by_table.setdefault(name, []).append(record_id)
        e = sqlio.escape
        for name, ids in by_table.items():
            target = snake(name)
            columns = self.columns[target]
            rows_fr, rows_en = self.rows(name), self.rows(name, 'enUS')
            values, locale_values = [], []
            # French texts go to the _locale table, only when the snapshot has French files
            locale_columns = self.columns.get(target + '_locale', []) if os.path.isdir(os.path.join(self.folder, 'frFR')) else []
            for record_id in ids:
                fr, en = rows_fr[record_id], rows_en.get(record_id, rows_fr[record_id])
                line = []
                for column in columns:
                    if column == 'VerifiedBuild':
                        line.append(str(self.build))
                    elif column in fr:
                        line.append(e(en[column] if isinstance(fr[column], str) else self.fit(target, column, fr[column])))
                    else:
                        line.append('0')
                values.append('(' + ','.join(line) + ')')
                if locale_columns:
                    texts = {c[:-5]: fr.get(c[:-5]) for c in locale_columns if c.endswith('_lang')}
                    if any(texts.values()):
                        line = []
                        for column in locale_columns:
                            if column == 'ID':
                                line.append(str(record_id))
                            elif column == 'locale':
                                line.append("'frFR'")
                            elif column == 'VerifiedBuild':
                                line.append(str(self.build))
                            else:
                                line.append(e(texts.get(column[:-5]) or ''))
                        locale_values.append('(' + ','.join(line) + ')')
                push.append([self.table_hash(name), record_id])
            id_list = ','.join(map(str, ids))
            apply.append(f"INSERT INTO `{target}` (`{'`,`'.join(columns)}`) VALUES\n" + ',\n'.join(values) + ';')
            rollback.append(f'DELETE FROM `{target}` WHERE ID IN ({id_list}) AND VerifiedBuild = {self.build};')
            if locale_values:
                apply.append(f"INSERT INTO `{target}_locale` (`{'`,`'.join(locale_columns)}`) VALUES\n" + ',\n'.join(locale_values) + ';')
                rollback.append(f"DELETE FROM `{target}_locale` WHERE ID IN ({id_list}) AND locale = 'frFR' AND VerifiedBuild = {self.build};")
        return '\n'.join(apply), '\n'.join(reversed(rollback)), len(plan), push


def generate(content, results, ctx, folder, build):
    """[(type, id, kind, db, rows, needs, summary, detail, sql_apply, sql_rollback)]"""
    log('forge: building fixes')
    fixes = []
    copier = Copier(folder, build)

    def failing(kind, entity_id, code):
        return any(c['code'] == code and not c['ok'] for c in results.get((kind, entity_id), (None, None, []))[2])

    # ---- hotfix: resources unknown to the core
    builders = {
        'item': lambda plan, i, ent: copier.item(plan, i),
        'spell': lambda plan, i, ent: copier.spell(plan, i),
        'recipe': lambda plan, i, ent: copier.spell(plan, i),
        'talent': lambda plan, i, ent: (copier.add(plan, 'Talent', i), [copier.spell(plan, s) for s in ent.get('ranks', [])]),
        'mount': lambda plan, i, ent: (copier.add(plan, 'Mount', i), [copier.add(plan, 'MountXDisplay', r['ID']) for r in copier.where('MountXDisplay', 'MountID', i)], copier.spell(plan, ent['spell'])),
        'pet': lambda plan, i, ent: (copier.add(plan, 'BattlePetSpecies', i), copier.spell(plan, ent['spell'])),
        'toy': lambda plan, i, ent: (copier.add(plan, 'Toy', i), copier.item(plan, ent['item'])),
        'achievement': lambda plan, i, ent: copier.achievement(plan, i),
    }
    hotfixed = set()
    for kind, build_plan in builders.items():
        for entity_id, entity in content.get(kind, {}).items():
            status = results.get((kind, entity_id))
            if not status or not (failing(kind, entity_id, 'core') or (kind == 'talent' and failing(kind, entity_id, 'ranks'))):
                continue
            plan = set()
            build_plan(plan, entity_id, entity)
            if not plan:
                continue
            apply, rollback, rows, push = copier.sql(plan)
            tables = sorted({name for name, _ in plan})
            summary = L(f'Copy {rows} official record(s) into hotfixes: ' + ', '.join(tables), f'Copier {rows} enregistrement(s) officiel(s) dans hotfixes : ' + ', '.join(tables))
            fixes.append((kind, entity_id, 'hotfix', 'hotfixes', rows, '', summary, {'tables': tables, 'push': push}, apply, rollback))
            hotfixed.add((kind, entity_id))

    # ---- trainer: class and profession spells nobody teaches
    trainer_npcs = ctx.get('trainer_npcs', {})
    by_trainer = {}
    for row in ctx['trainer_rows']:
        by_trainer.setdefault(row['SpellId'], []).append(row)
    abilities = table(folder, 'SkillLineAbility')
    by_spell, by_line = {}, {}
    for a in abilities:
        by_spell.setdefault(a['Spell'], []).append(a)
        by_line.setdefault(a['SkillLine'], []).append(a)
    levels = {r['SpellID']: r for r in table(folder, 'SpellLevels') if r['DifficultyID'] == 0}
    skill_lines = {r['ID']: r for r in table(folder, 'SkillLine')}
    skill_lines_en = {r['ID']: r for r in table(folder, 'SkillLine', 'enUS')}
    candidates = [('spell', s, e) for s, e in content.get('spell', {}).items() if e['sub'] in ('class', 'profession')] + \
                 [('recipe', s, e) for s, e in content.get('recipe', {}).items()]
    for kind, spell_id, entity in candidates:
        if not failing(kind, spell_id, 'learn') or entity.get('auto') or entity.get('teach'):
            continue  # spells Blizzard teaches with an item get a vendor fix for that item instead
        rows = by_spell.get(spell_id, [])
        if not rows or any(r['AcquireMethod'] in (1, 2) for r in rows):
            continue
        ability = rows[0]
        line_en = skill_lines_en.get(ability['SkillLine'], {}).get('DisplayName', '')
        if line_en == 'Beast Training' or line_en.startswith('Pet -'):
            continue  # hunter pet abilities are learned through pet training, not at trainers
        siblings = [row for a in by_line.get(ability['SkillLine'], []) for row in by_trainer.get(a['Spell'], []) if row['TrainerId'] in trainer_npcs]
        trainers = sorted({row['TrainerId'] for row in siblings})
        if not trainers:
            continue
        level_row = levels.get(spell_id, {})
        level = level_row.get('BaseLevel') or level_row.get('SpellLevel') or 0
        profession = skill_lines.get(ability['SkillLine'], {}).get('CategoryID') in (9, 11)
        req_line, req_rank = (ability['SkillLine'], ability['MinSkillLineRank']) if profession else (0, 0)
        if profession:
            near = [row['MoneyCost'] for row in siblings if abs(row['ReqSkillRank'] - req_rank) <= 25]
        else:
            near = [row['MoneyCost'] for row in siblings if abs(row['ReqLevel'] - level) <= 3]
        near = near or [row['MoneyCost'] for row in siblings]
        cost = int(round(statistics.median(near) / 10.0) * 10) if near else 0
        previous = ability['SupercedesSpell'] if ability['SupercedesSpell'] in content.get('spell', {}) else 0
        values = ',\n'.join(f'({t},{spell_id},{cost},{req_line},{req_rank},{previous},0,0,{min(level, 255)},{build})' for t in trainers)
        apply = 'INSERT INTO `trainer_spell` (`TrainerId`,`SpellId`,`MoneyCost`,`ReqSkillLine`,`ReqSkillRank`,`ReqAbility1`,`ReqAbility2`,`ReqAbility3`,`ReqLevel`,`VerifiedBuild`) VALUES\n' + values + ';'
        rollback = f"DELETE FROM `trainer_spell` WHERE SpellId = {spell_id} AND TrainerId IN ({','.join(map(str, trainers))});"
        name_fr = skill_lines.get(ability['SkillLine'], {}).get('DisplayName', str(ability['SkillLine']))
        name_en = skill_lines_en.get(ability['SkillLine'], {}).get('DisplayName') or name_fr
        requirement_en = f'skill {req_rank}' if profession else f'level {level}'
        requirement_fr = f'compétence {req_rank}' if profession else f'niveau {level}'
        summary = L(f'Teach it at {len(trainers)} {name_en} trainer(s), {requirement_en}, {money(cost, "g", "s", "c")}',
                    f'L’enseigner chez {len(trainers)} entraîneur(s) {name_fr}, {requirement_fr}, {money(cost, "po", "pa", "pc")}')
        needs = 'hotfix' if (kind, spell_id) in hotfixed else ''
        fixes.append((kind, spell_id, 'trainer', 'world', len(trainers), needs, summary,
                      {'trainers': trainers, 'cost': cost, 'level': level, 'skill': req_line, 'rank': req_rank, 'previous': previous}, apply, rollback))

    # ---- instance_template for dungeons and raids
    for map_id, entity in content.get('dungeon', {}).items():
        if entity['kind'] in (1, 2) and failing('dungeon', map_id, 'instance_template'):
            parent = entity.get('parent', 0)
            apply = f"INSERT INTO `instance_template` (`map`,`parent`,`script`) VALUES ({map_id},{parent},'');"
            rollback = f'DELETE FROM `instance_template` WHERE map = {map_id};'
            summary = L(f'Create the instance_template row (parent map {parent}, no script yet)', f'Créer la ligne instance_template (carte parente {parent}, sans script)')
            fixes.append(('dungeon', map_id, 'instance', 'world', 1, '', summary, {'parent': parent}, apply, rollback))
    log(f"forge: {len(fixes)} fixes ({', '.join(f'{k}={sum(1 for f in fixes if f[2] == k)}' for k in ('hotfix', 'trainer', 'instance'))})")
    return fixes
